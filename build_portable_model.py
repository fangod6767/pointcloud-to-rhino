"""Extract upstream RandLA-Net inference graph without Open3D compiled ML ops.

All learned layers and forward operations are retained from the pinned source.
Only training/data-pipeline dependencies are removed. See vendor/open3d_ml/LICENSE.
"""
from pathlib import Path
import ast
ROOT=Path(__file__).parent
tree=ast.parse((ROOT/'vendor/open3d_ml/randlanet.py').read_text(encoding='utf8'))
classes=[]
for node in tree.body:
    if not isinstance(node,ast.ClassDef):continue
    if node.name=='RandLANet':
        node.body=[m for m in node.body if isinstance(m,ast.FunctionDef) and m.name in ['__init__','forward','random_sample','nearest_interpolation']]
        init=next(m for m in node.body if m.name=='__init__')
        init.body=[s for s in init.body if not (isinstance(s,ast.Assign) and any(isinstance(t,ast.Attribute) and t.attr=='augmenter' for t in s.targets))]
    classes.append(node)
header='''# Adapted from Open3D-ML (MIT); see vendor/open3d_ml/LICENSE.
# Generated by build_portable_model.py from pinned upstream source.
import torch
import torch.nn as nn
import numpy as np
from types import SimpleNamespace

class BaseModel(nn.Module):
    def __init__(self, **kwargs):
        super().__init__()
        self.cfg = SimpleNamespace(**kwargs)
    @property
    def device(self):
        return next(self.parameters()).device

'''
(ROOT/'randlanet_portable.py').write_text(header+'\n\n'.join(ast.unparse(c) for c in classes)+'\n',encoding='utf8')
print('Created portable inference module from',len(classes),'upstream classes')
